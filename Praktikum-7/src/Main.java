    private void CBPaketStudioActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_CBPaketStudioActionPerformed
        Object selectedItem = CBPaketStudio.getSelectedItem();
    
    // Cegah error jika belum ada item yang dipilih (null)
    if (selectedItem == null) {
        return;
    }

    String paket = selectedItem.toString();

    switch (paket) {
        case "Paket Reguler":
            CBLamaSewa.setSelectedItem("2");
            break;
        case "Paket Premium":
            CBLamaSewa.setSelectedItem("3");
            break;
        default:
            // Opsional: biarkan lama sewa seperti semula
            break;
    }
    }//GEN-LAST:event_CBPaketStudioActionPerformed


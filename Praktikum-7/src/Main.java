    private void BDetailActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BDetailActionPerformed
        String nama = TFNamaPenyewa.getText().trim();
        String paket = (String) CBPaketStudio.getSelectedItem();
        String lamaSewaStr = (String) CBLamaSewa.getSelectedItem();

        if (nama.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, 
                "Nama Penyewa tidak boleh kosong!", "Error", 
                javax.swing.JOptionPane.ERROR_MESSAGE);
            return;
        }

        int lamaSewa;
        try {
            lamaSewa = Integer.parseInt(lamaSewaStr);
        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this, 
                "Lama sewa tidak valid!", "Error", 
                javax.swing.JOptionPane.ERROR_MESSAGE);
            return;
        }

        int totalMenit = lamaSewa * 60;

        // Tampilkan di panel detail
        LabelPenyewa.setText(nama);
        LabelPaketStudio.setText(paket);
        LabelLamaSewa.setText(String.valueOf(lamaSewa));
        LabelTotalDurasi.setText(String.valueOf(totalMenit));
    }//GEN-LAST:event_BDetailActionPerformed


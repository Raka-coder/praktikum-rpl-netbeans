    private void BCreateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BCreateActionPerformed
        try {
            String sql = "INSERT INTO contact (nama, telepon, email) VALUES (?, ?, ?)";
            PreparedStatement pst = cn.prepareStatement(sql);
            pst.setString(1, TFNama.getText());
            pst.setString(2, TFNoTelepon.getText());
            pst.setString(3, TFEmail.getText());
            pst.executeUpdate();

            JOptionPane.showMessageDialog(null, "Data berhasil ditambahkan!");
            loadTable();
            resetForm();

        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, e.getMessage());
        }
    }//GEN-LAST:event_BCreateActionPerformed

    private void BUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BUpdateActionPerformed
        int row = TContact.getSelectedRow();
        if (row == -1) {
            JOptionPane.showMessageDialog(null, "Pilih data yang ingin diupdate!");
            return;
        }

        try {
            String id = TContact.getValueAt(row, 0).toString(); // Ambil ID asli dari kolom tersembunyi

            String sql = "UPDATE contact SET nama=?, telepon=?, email=? WHERE id=?";
            PreparedStatement pst = cn.prepareStatement(sql);
            pst.setString(1, TFNama.getText());
            pst.setString(2, TFNoTelepon.getText());
            pst.setString(3, TFEmail.getText());
            pst.setString(4, id);
            pst.executeUpdate();

            JOptionPane.showMessageDialog(null, "Data berhasil diperbarui!");
            loadTable();
            resetForm();

        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, "Error: " + e.getMessage());
        }
    }//GEN-LAST:event_BUpdateActionPerformed

    private void BDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BDeleteActionPerformed
        int row = TContact.getSelectedRow();
        if (row == -1) {
            JOptionPane.showMessageDialog(null, "Pilih data yang ingin dihapus!");
            return;
        }

        int confirm = JOptionPane.showConfirmDialog(null,
                "Yakin ingin menghapus data?",
                "Hapus Data",
                JOptionPane.YES_NO_OPTION);

        if (confirm == JOptionPane.YES_OPTION) {
            try {
                String id = TContact.getValueAt(row, 0).toString(); // ID asli

                String sql = "DELETE FROM contact WHERE id=?";
                PreparedStatement pst = cn.prepareStatement(sql);
                pst.setString(1, id);
                pst.executeUpdate();

                JOptionPane.showMessageDialog(null, "Data berhasil dihapus!");
                loadTable();
                resetForm();

            } catch (Exception e) {
                JOptionPane.showMessageDialog(null, "Error: " + e.getMessage());
            }
        }
    }//GEN-LAST:event_BDeleteActionPerformed


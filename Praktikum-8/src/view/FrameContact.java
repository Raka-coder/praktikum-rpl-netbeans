    public void loadTable() {
        DefaultTableModel model = new DefaultTableModel() {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false; // Membuat tabel tidak editable
            }
        };

        // Tambahkan kolom "id" secara internal (akan disembunyikan)
        model.addColumn("id"); // Kolom 0 → ID asli (tidak ditampilkan)
        model.addColumn("No"); // Kolom 1
        model.addColumn("Nama"); // Kolom 2
        model.addColumn("Telepon"); // Kolom 3
        model.addColumn("Email"); // Kolom 4

        try {
            String sql = "SELECT * FROM contact";
            Statement stm = cn.createStatement();
            ResultSet res = stm.executeQuery(sql);

            int no = 1;
            while (res.next()) {
                model.addRow(new Object[]{
                    res.getString("id"),
                    no++,
                    res.getString("nama"),
                    res.getString("telepon"),
                    res.getString("email")
                });
            }

            TContact.setModel(model);

            TContact.getColumnModel().getColumn(0).setMinWidth(0);
            TContact.getColumnModel().getColumn(0).setMaxWidth(0);
            TContact.getColumnModel().getColumn(0).setWidth(0);

        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, e.getMessage());
        }
    }

